#!/usr/bin/env python3
# mkrom.py BIN OUT.vhd -- [system_z1013-10] the portable stand-in for the source project's Gowin_Z1013_ROM: the same
# entity name and ports, the same behaviour as the four Gowin pROM banks (READ_MODE 0: the word of the address
# registered on clk while ce, reset synchronous; the bank chosen by the CURRENT ad(12 downto 11), as the original's
# output mux does), its contents generated from z1013_boot_rom.bin -- never typed by hand.
import sys
data = open(sys.argv[1], 'rb').read()
assert len(data) == 8192, "the boot ROM is 8 KiB"
def bank(i):
    words = data[i * 2048:(i + 1) * 2048]
    rows = [", ".join('x"%02X"' % b for b in words[r:r + 16]) for r in range(0, 2048, 16)]
    return "(\n        " + ",\n        ".join(rows) + ")"
out = f"""-- Gowin_Z1013_ROM.vhd -- GENERATED by mkrom.py from z1013_boot_rom.bin; do not edit.
-- A portable stand-in for src/gowin_rom/gowin_z1013_rom.vhd (Gowin pROM cells): the same entity and ports, four
-- 2 KiB banks read registered (Gowin READ_MODE 0), the bank picked by the current ad(12 downto 11).
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity Gowin_Z1013_ROM is
    port (
        dout: out std_logic_vector(7 downto 0);
        clk: in std_logic;
        oce: in std_logic;
        ce: in std_logic;
        reset: in std_logic;
        ad: in std_logic_vector(12 downto 0)
    );
end Gowin_Z1013_ROM;

architecture Behavioral of Gowin_Z1013_ROM is
    type bank_t is array (0 to 2047) of std_logic_vector(7 downto 0);
    constant BANK_0 : bank_t := {bank(0)};
    constant BANK_1 : bank_t := {bank(1)};
    constant BANK_2 : bank_t := {bank(2)};
    constant BANK_3 : bank_t := {bank(3)};
    signal do_0, do_1, do_2, do_3 : std_logic_vector(7 downto 0) := (others => '0');
begin
    process (clk)
        variable a : integer range 0 to 2047;
    begin
        if rising_edge(clk) then
            a := to_integer(unsigned(ad(10 downto 0)));
            if reset = '1' then
                do_0 <= (others => '0'); do_1 <= (others => '0'); do_2 <= (others => '0'); do_3 <= (others => '0');
            elsif ce = '1' then
                do_0 <= BANK_0(a); do_1 <= BANK_1(a); do_2 <= BANK_2(a); do_3 <= BANK_3(a);
            end if;
        end if;
    end process;

    with ad(12 downto 11) select
        dout <=
            do_0 when "00",
            do_1 when "01",
            do_2 when "10",
            do_3 when others;
end Behavioral;
"""
open(sys.argv[2], 'w').write(out)
